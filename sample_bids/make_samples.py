def blank_pdf(path):
    w = PdfWriter()
    w.add_blank_page(595, 842)  # หน้าเปล่า จำลองไฟล์สแกนที่ไม่มีข้อความ
    buf = io.BytesIO()
    w.write(buf)
    with open(path, "wb") as f:
        f.write(buf.getvalue())


