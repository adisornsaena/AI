def tax_id(d12):
    s = sum(int(c) * (13 - i) for i, c in enumerate(d12))
    return d12 + str((11 - s % 11) % 10)


def fmt(d):
    return f"{d[0]}-{d[1:5]}-{d[5:10]}-{d[10:12]}-{d[12]}"


